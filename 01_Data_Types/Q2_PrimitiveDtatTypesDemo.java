
 // Write a program to declare variables of all primitive data types and print them.
 
public class Q2_PrimitiveDtatTypesDemo {
    public static void main(String[] args) {
        
        byte b = 127;
        short s = 456;
        int i = 1000;
        long l = 4000;
        float f = 12.06f;
        double d = 123.654;
        char ch = 'R';
       boolean bol = true;
       System.out.println("This is your all primtive data types: ");
       System.out.println("Byte: " +b);
       System.out.println("short: " +s);
       System.out.println("int: " +i);
       System.out.println("long: " +l);
       System.out.println("float : " +f);
       System.out.println("double : " +d);
       System.out.println("char: " +ch);
       System.out.println("boolean : " + bol);


    }
}
