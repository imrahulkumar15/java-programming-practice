// Write a Java program to create an integer array of 5 elements and print all the elements using a loop.

public class Q01_PrintElementsOfNo {
    public static void main(String[] args) {
        int arr[]= new int[] {10,20,30,40,50};// Declare Arry
        int i; // initiliztion
        for(i=0;i<5;i++) // condition 
            System.out.println(arr[i]);// print Result 
    }
}
